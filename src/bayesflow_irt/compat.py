"""Load checkpoints across the bayesflow attention rename.

Between bayesflow 2.0.8 and 2.0.10 two summary-network layer classes were
renamed: ``InducedSetAttentionBlock`` became ``InducedSetAttention`` and
``SetAttentionBlock`` became ``SetAttention``. The implementations are
identical -- same ``add_weight`` call for the inducing points, same
``mab0``/``mab1`` sublayers, same forward pass -- so the change is cosmetic
for computation.

It is not cosmetic for checkpoints. Keras keys a layer held in a **container**
by its class name, deliberately and not by ``layer.name``
(``keras/src/saving/saving_lib.py``, ``_save_container_state``: "Do NOT
address the saveable via `saveable.name`, since names are usually
autogenerated and thus not reproducible"). ``MatrixEquivariantIRTSummary``
keeps its attention stack in a list, so the rename moved those weights'
paths: a checkpoint written under 2.0.8 stores them under
``induced_set_attention_block`` while one written under 2.0.10 uses
``induced_set_attention``. Loading across that boundary fails on the whole
subtree::

    ValueError: A total of 25 objects could not be loaded.
    Layer 'induced_set_attention' expected 1 variables, but received 0

Pinning the class name to one spelling would break checkpoints saved with
the other; tolerating both on load breaks nothing.

The silent case is the dangerous one. ``bayesflow_hpo``'s checkpoint loader
swallows this failure, so a caller that does not compare weight digests before
and after loading carries on with a randomly initialised network and reports
its metrics as the trial's. :func:`load_weights_compat` raises instead, and
:func:`weights_digest` is exported so callers of *that* loader can run the
before/after comparison themselves.
"""

from __future__ import annotations

import hashlib
import re
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

__all__ = [
    "SIZE_MOMENTS_CHANGED_AT",
    "adapter_size_moments",
    "apply_checkpoint_size_moments",
    "legacy_log_size_moments",
    "legacy_size_moments",
    "load_weights_compat",
    "resolve_checkpoint_size_moments",
    "set_adapter_size_moments",
    "weights_digest",
]

#: When ``adapters._log_size_moments`` changed.
#: A weights-only checkpoint trained before this instant saw size conditions
#: standardized with :func:`legacy_log_size_moments`.
SIZE_MOMENTS_CHANGED_AT = datetime(
    2026, 10, 5, 13, 8, 58, tzinfo=timezone(timedelta(hours=2))
)

_SIZE_KEYS = ("n_items", "n_persons")

#: Class names as they were before the rename, mapped to their replacements.
#: Keras snake_cases the class name and appends ``_1``, ``_2`` ... to
#: disambiguate repeats within one container, so both spellings are matched
#: with an optional numeric suffix.
_OLD_TO_NEW = {
    "induced_set_attention_block": "induced_set_attention",
    "set_attention_block": "set_attention",
}
_NEW_TO_OLD = {new: old for old, new in _OLD_TO_NEW.items()}

_SUFFIX = re.compile(r"^(?P<base>.+?)(?P<suffix>_\d+)?$")


def weights_digest(model: Any) -> str:
    """Return a short digest of ``model``'s current weight values.

    Comparing this before and after a load is the only reliable way to tell a
    real restore from a swallowed failure.
    """
    import numpy as np

    h = hashlib.sha256()
    for variable in model.weights:
        h.update(np.ascontiguousarray(np.asarray(variable)).tobytes())
    return h.hexdigest()[:16]


def _snapshot(model: Any) -> list[Any]:
    """Copy ``model``'s weight values, for rolling back a failed load."""
    import numpy as np

    # `np.asarray(...).copy()` rather than `np.array(..., copy=True)`: a Keras
    # variable's `__array__` does not accept the `copy` keyword and warns.
    return [np.asarray(variable).copy() for variable in model.weights]


def _restore(model: Any, snapshot: list[Any]) -> None:
    """Assign a :func:`_snapshot` back onto ``model``."""
    for variable, value in zip(model.weights, snapshot, strict=True):
        variable.assign(value)


def _rename_component(component: str, mapping: dict[str, str]) -> str:
    """Rename one path component, preserving any ``_<n>`` uniquifier."""
    match = _SUFFIX.match(component)
    if match is None:  # pragma: no cover - the pattern matches any string
        return component
    base = match.group("base")
    if base not in mapping:
        return component
    return mapping[base] + (match.group("suffix") or "")


def _reject_unsafe_storage(file: Any) -> None:
    """Raise ``ValueError`` if ``file`` points outside itself for data.

    Keras refuses HDF5 datasets with external storage
    (``keras.src.saving.saving_lib.H5Entry._verify_dataset``, the 3.12.1
    loading safeguard). :func:`_rewrite` reads every dataset into memory, so
    without the same check a crafted checkpoint could copy the bytes of an
    arbitrary local file into the rewritten weights. External links and
    virtual datasets are rejected for the same reason. Nothing is read.
    """
    import h5py

    # Collected and raised afterwards: an exception inside an h5py visitor
    # callback surfaces as a SystemError from the C layer.
    problems: list[str] = []

    def check_link(name: str, link: Any) -> None:
        if isinstance(link, h5py.ExternalLink):
            problems.append(f"Not allowed: H5 external link at {name!r}")

    def check_dataset(name: str, obj: Any) -> None:
        if isinstance(obj, h5py.Dataset) and (obj.external or obj.is_virtual):
            problems.append(
                f"Not allowed: H5 dataset {name!r} with external or virtual storage"
            )

    file.visititems_links(check_link)
    file.visititems(check_dataset)
    if problems:
        raise ValueError("; ".join(problems))


def _rewrite(source: Path, destination: Path, mapping: dict[str, str]) -> bool:
    """Copy ``source`` to ``destination`` with layer paths renamed.

    Returns whether any path actually changed; a copy that renamed nothing is
    not worth retrying with.
    """
    import h5py

    changed = False
    with h5py.File(source, "r") as src:
        _reject_unsafe_storage(src)
    with h5py.File(source, "r") as src, h5py.File(destination, "w") as dst:
        dst.attrs.update(src.attrs)

        def visit(name: str, obj: Any) -> None:
            nonlocal changed
            renamed = "/".join(
                _rename_component(part, mapping) for part in name.split("/")
            )
            if renamed != name:
                changed = True
            if isinstance(obj, h5py.Dataset):
                out = dst.create_dataset(renamed, data=obj[()])
            else:
                out = dst.require_group(renamed)
            out.attrs.update(obj.attrs)

        src.visititems(visit)
    return changed


def load_weights_compat(model: Any, filepath: str | Path) -> str:
    """Load ``filepath`` into ``model``, tolerating the attention rename.

    Tries a direct load first. If that fails, retries against a temporary copy
    whose attention-layer paths have been renamed to the other spelling. The
    renaming is lossless: the two implementations hold the same variables in
    the same order, so only the keys differ.

    Parameters
    ----------
    model : keras.Model
        A built model, as produced by the study's ``build_fn``. It must have
        been called once so its weights exist.
    filepath : str or pathlib.Path
        A ``.weights.h5`` checkpoint. ``.keras`` archives are not handled
        here: they carry their own config and are loaded by
        ``keras.saving.load_model``.

    Returns
    -------
    str
        ``"direct"`` if the file loaded as written, otherwise
        ``"renamed:<old>->new"`` or ``"renamed:new-><old>"`` naming the
        direction that worked.

    Raises
    ------
    ValueError
        If the file has datasets with external or virtual storage, or
        external links, which Keras itself refuses to load. The model is
        rolled back first, and the rename fallback never reads such a file.
    RuntimeError
        If no spelling restores the weights. ``model`` is rolled back to the
        values it held on entry first, and the message carries the original
        error, since that names the layers that did not match.

    Notes
    -----
    Success is "``load_weights`` did not raise", not "the values changed".
    Keras raises on a key mismatch, and a model that already holds the
    checkpoint's values -- a second load, or a save followed immediately by a
    load -- is a correct restore that changes nothing. Use
    :func:`weights_digest` directly to answer the different question of
    whether a *wrapper* that swallows load errors, as ``bayesflow_hpo``'s
    does, actually restored anything.
    """
    path = Path(filepath)
    # Keras assigns weights as it walks the saveable tree and only raises once
    # the walk is finished, so a failed attempt can leave the model partly
    # overwritten -- and the next attempt starts from that state. Snapshot so
    # the all-failed path can hand back the model it was given rather than a
    # half-restored one.
    snapshot = _snapshot(model)

    direct_error: Exception | None = None
    try:
        model.load_weights(str(path))
    except Exception as error:  # noqa: BLE001 - retried below, reported if all fail
        direct_error = error
    else:
        return "direct"

    attempts = (("old->new", _OLD_TO_NEW), ("new->old", _NEW_TO_OLD))
    with tempfile.TemporaryDirectory(prefix="bfirt-compat-") as tmp:
        for index, (label, mapping) in enumerate(attempts):
            # Numbered rather than named after the label: `>` is not a legal
            # filename character on Windows.
            candidate = Path(tmp) / f"attempt{index}.weights.h5"
            try:
                renamed = _rewrite(path, candidate, mapping)
            except ValueError:
                _restore(model, snapshot)
                raise
            if not renamed:
                continue
            _restore(model, snapshot)
            try:
                model.load_weights(str(candidate))
            except Exception:  # noqa: BLE001 - try the other direction
                continue
            return f"renamed:{label}"

    _restore(model, snapshot)
    raise RuntimeError(
        f"{path}: could not restore weights under either attention spelling. "
        "The model has been rolled back to the weights it held before this "
        f"call ({weights_digest(model)}). Original error: {direct_error!r}"
    )


# ---------------------------------------------------------------------------
# Size-condition moments of weights-only checkpoints
# ---------------------------------------------------------------------------
#
# A weights-only checkpoint (``weights.weights.h5`` + ``checkpoint.json``)
# carries no adapter; readers rebuild it from the study config with the
# *current* code. ``adapters._log_size_moments`` changed (the mean/sd used to
# standardize ``log(n_items)`` / ``log(n_persons)`` in
# ``_standardize_size_conditions``; see ``SIZE_MOMENTS_CHANGED_AT``).
# A checkpoint trained earlier therefore receives different size conditions
# on reload and may be mis-scored. Full
# ``.keras`` saves serialize the adapter and are unaffected.


def legacy_log_size_moments(
    value_range: tuple[int, int], bucket: int | None
) -> tuple[float, float]:
    """Mean and sd of ``log(size)`` as computed before the size-moments change.

    The support is every integer in ``[lo, hi]`` when ``bucket`` is ``None``,
    otherwise one representative per bucket,
    ``min(lo + i * bucket + bucket - 1, hi)`` for
    ``i = 0 .. ceil((hi - lo + 1) / bucket) - 1`` (the bucket's upper edge).
    The moments are the unweighted mean and the population standard deviation
    (``np.std``) of ``log(support)``; the sd is forced to 1.0 when it is 0.

    Parameters
    ----------
    value_range : tuple of int
        Inclusive ``(lo, hi)`` size range.
    bucket : int or None
        Bucket width, or ``None`` for unbucketed sizes.

    Returns
    -------
    tuple of float
        ``(mean, std)``.
    """
    import math

    import numpy as np

    lo, hi = int(value_range[0]), int(value_range[1])
    if bucket is None:
        support = np.arange(lo, hi + 1, dtype=np.float64)
    else:
        n = math.ceil((hi - lo + 1) / bucket)
        support = np.array(
            [min(lo + i * bucket + bucket - 1, hi) for i in range(n)],
            dtype=np.float64,
        )
    logs = np.log(support)
    std = float(np.std(logs))
    return float(np.mean(logs)), std if std > 0 else 1.0


def legacy_size_moments(simulator: Any) -> dict[str, list[float]]:
    """Pre-change moments for ``n_items`` and ``n_persons`` of ``simulator``.

    Uses ``simulator.n_items`` / ``item_bucket`` and ``simulator.n_persons`` /
    ``person_bucket`` with :func:`legacy_log_size_moments`.

    Returns
    -------
    dict
        ``{"n_items": [mean, std], "n_persons": [mean, std]}``.
    """
    pairs = (("n_items", "item_bucket"), ("n_persons", "person_bucket"))
    return {
        key: list(
            legacy_log_size_moments(
                getattr(simulator, key), getattr(simulator, bucket_attr, None)
            )
        )
        for key, bucket_attr in pairs
    }


def _size_standardize_transform(adapter: Any, key: str) -> Any:
    """The adapter's ``Standardize`` transform for ``key``, or ``None``."""
    from bayesflow.adapters.transforms import Standardize

    for transform in adapter.transforms:
        if (
            getattr(transform, "include", None) == [key]
            and getattr(transform, "transform_constructor", None) is Standardize
        ):
            return transform
    return None


def adapter_size_moments(adapter: Any) -> dict[str, list[float]]:
    """Mean and sd that ``adapter`` uses to standardize the size conditions.

    Record this next to a weights-only checkpoint (``checkpoint.json``) so a
    later reader can restore exactly the conditions the network was trained
    with, whatever the current ``_log_size_moments`` computes.

    Returns
    -------
    dict
        ``{"n_items": [mean, std], "n_persons": [mean, std]}`` as plain floats.

    Raises
    ------
    ValueError
        If the adapter has no ``Standardize`` transform for a size key.
    """
    out: dict[str, list[float]] = {}
    for key in _SIZE_KEYS:
        transform = _size_standardize_transform(adapter, key)
        if transform is None:
            raise ValueError(f"adapter has no Standardize transform for {key!r}")
        out[key] = [
            float(transform.kwargs["mean"]),
            float(transform.kwargs["std"]),
        ]
    return out


def set_adapter_size_moments(adapter: Any, moments: dict[str, Any]) -> None:
    """Overwrite the size-condition moments of ``adapter`` in place.

    Replaces the ``mean`` / ``std`` kwargs of the ``Standardize`` transforms
    for the keys in ``moments`` (as ``np.float32``) and clears their lazily
    filled ``transform_map`` cache, so the new values take effect on the next
    call.

    Parameters
    ----------
    adapter : bayesflow.adapters.Adapter
        An adapter built by one of the ``make_*_adapter`` factories.
    moments : dict
        ``{key: [mean, std]}`` as returned by :func:`adapter_size_moments`.

    Raises
    ------
    ValueError
        If a key's ``Standardize`` transform is missing. Nothing is modified
        in that case.
    """
    import numpy as np

    targets = {}
    for key in moments:
        transform = _size_standardize_transform(adapter, key)
        if transform is None:
            raise ValueError(f"adapter has no Standardize transform for {key!r}")
        targets[key] = transform
    for key, transform in targets.items():
        mean, std = moments[key]
        transform.kwargs = {
            **transform.kwargs,
            "mean": np.float32(mean),
            "std": np.float32(std),
        }
        transform.transform_map = {}


def resolve_checkpoint_size_moments(
    record: dict[str, Any],
    simulator: Any,
    trained_at: datetime | None = None,
) -> dict[str, list[float]] | None:
    """Decide which size moments a weights-only checkpoint was trained with.

    Precedence: moments recorded in ``record["adapter_size_moments"]``; else,
    if ``trained_at`` is earlier than :data:`SIZE_MOMENTS_CHANGED_AT`, the
    :func:`legacy_size_moments` of ``simulator``; else ``None``.

    Parameters
    ----------
    record : dict
        The checkpoint's ``checkpoint.json`` contents (may be empty).
    simulator : object
        The simulator the adapter was built from.
    trained_at : datetime, optional
        When training finished. Must be timezone-aware to be compared.

    Returns
    -------
    dict or None
        Moments to apply with :func:`set_adapter_size_moments`, or ``None``
        meaning the current code's moments apply unchanged.
    """
    if record and "adapter_size_moments" in record:
        return record["adapter_size_moments"]
    if trained_at is not None and trained_at < SIZE_MOMENTS_CHANGED_AT:
        return legacy_size_moments(simulator)
    return None


def apply_checkpoint_size_moments(
    adapter: Any,
    simulator: Any,
    mode: str = "auto",
    record: dict[str, Any] | None = None,
    trained_at: datetime | None = None,
) -> str:
    """Set ``adapter``'s size moments for a weights-only checkpoint.

    For code that rebuilds an adapter from a study config and then loads
    ``weights.weights.h5``.

    Parameters
    ----------
    adapter, simulator
        As for :func:`set_adapter_size_moments` /
        :func:`resolve_checkpoint_size_moments`.
    mode : {"auto", "current", "legacy"}
        ``"auto"`` uses :func:`resolve_checkpoint_size_moments`;
        ``"current"`` leaves the adapter as built; ``"legacy"`` forces
        :func:`legacy_size_moments`.
    record : dict, optional
        The checkpoint's ``checkpoint.json`` contents.
    trained_at : datetime, optional
        When the checkpoint was trained. A naive value (as Optuna's
        ``datetime_complete``) is read in the UTC offset of
        :data:`SIZE_MOMENTS_CHANGED_AT`.

    Returns
    -------
    str
        A one-line description of which moments are in effect.
    """
    if mode not in ("auto", "current", "legacy"):
        raise ValueError(f"mode must be auto, current or legacy; got {mode!r}")
    if trained_at is not None and trained_at.tzinfo is None:
        trained_at = trained_at.replace(tzinfo=SIZE_MOMENTS_CHANGED_AT.tzinfo)
    if mode == "current":
        return "current code"
    if mode == "legacy":
        moments = legacy_size_moments(simulator)
        label = "legacy size moments (forced)"
    else:
        moments = resolve_checkpoint_size_moments(record or {}, simulator, trained_at)
        label = (
            "from checkpoint"
            if record and "adapter_size_moments" in record
            else "legacy size moments"
        )
    if moments is None:
        return "current code"
    set_adapter_size_moments(adapter, moments)
    return f"{label}: {moments}"
